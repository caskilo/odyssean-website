// Copy verified PDFs to public/files/<readable>.pdf and write the legacy-URL map used to
// generate .htaccess 301s (build-plan task 1.9 → 8.5). Every discovered Wix PDF URL is covered.
import { copyFile, mkdir, writeFile, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { CACHE, SITE, PDFS, pdfPath, ROUTES } from './lib.mjs';

const pub = join(SITE, 'public', 'files');
await mkdir(pub, { recursive: true });
const done = new Set();
for (const [id, name] of Object.entries(PDFS)) {
  if (done.has(name)) continue;
  await copyFile(join(CACHE, 'pdfs', `${id}.pdf`), join(pub, `${name}.pdf`));
  done.add(name);
}

const links = JSON.parse(await readFile(join(CACHE, 'pdfs', 'pdf-links.json'), 'utf8'));
const unmapped = Object.keys(links).filter((id) => !PDFS[id]);
if (unmapped.length) throw new Error(`discovered PDFs without a mapping: ${unmapped.join(', ')}`);

const legacy = {
  note: 'Old Wix URL → new path. Source for .htaccess 301s. Generated by tools/extract/publish-pdfs.mjs; pages section maintained from build-plan B.2.',
  pages: ROUTES,
  posts: 'unchanged: /post/<slug> keeps its exact path',
  feeds: { '/blog-feed.xml': '/blog-feed.xml' },
  pdfs: Object.fromEntries(Object.keys(PDFS).map((id) => [`/_files/ugd/${id}.pdf`, pdfPath(id)])),
};
await mkdir(join(SITE, 'tools', 'redirects'), { recursive: true });
await writeFile(
  join(SITE, 'tools', 'redirects', 'legacy.json'),
  JSON.stringify(legacy, null, 2) + '\n',
);
console.log(
  `${done.size} files published, ${Object.keys(legacy.pdfs).length} legacy PDF URLs mapped`,
);
