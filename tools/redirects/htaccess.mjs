// Generates dist/.htaccess for Mythic Beasts (Apache): clean URLs, legacy redirects, security headers,
// caching. Redirect sources live in tools/redirects/legacy.json (build-plan B.2). Runs after `astro build`.
//   node tools/redirects/htaccess.mjs
// Staging: set STAGING_AUTH_FILE to the absolute path of an .htpasswd on the host (kept outside the web
// root) to add a password prompt and a noindex header. Production builds leave it unset.
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SITE_URL = 'https://www.odysseaninstitute.org';

const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** [source path, target] pairs from legacy.json. Entries that map to themselves are skipped. */
function legacyRedirects(legacy) {
  return [
    ...Object.entries(legacy.pages),
    ...Object.entries(legacy.feeds),
    ...Object.entries(legacy.pdfs),
  ].filter(([from, to]) => from !== to);
}

function buildHtaccess(legacy) {
  const redirects = legacyRedirects(legacy)
    .map(([from, to]) => {
      const flags = from.endsWith('.pdf') ? 'R=301,L,QSD,NE' : 'R=301,L,NE';
      const pattern = escapeRegex(from.slice(1)) + (from.endsWith('.pdf') ? '' : '/?');
      return `RewriteRule ^${pattern}$ ${to} [${flags}]`;
    })
    .join('\n');

  const auth = process.env.STAGING_AUTH_FILE;
  const staging = auth
    ? `
# Staging only: private test site
AuthType Basic
AuthName "Odyssean Institute (private test site)"
AuthUserFile ${auth}
Require valid-user
<IfModule mod_headers.c>
  Header always set X-Robots-Tag "noindex, nofollow"
</IfModule>
`
    : '';

  return `# Generated by tools/redirects/htaccess.mjs. Do not edit by hand.
Options -Indexes -MultiViews
DirectorySlash Off
DirectoryIndex index.html
ErrorDocument 404 /404.html

RewriteEngine On
RewriteBase /

# Canonical host
RewriteCond %{HTTP_HOST} ^odysseaninstitute\\.org$ [NC]
RewriteRule ^(.*)$ ${SITE_URL}/$1 [R=301,L]

# No trailing slashes (site uses trailingSlash: never)
RewriteRule ^(.+)/$ /$1 [R=301,L]

# Legacy Wix URLs (build-plan B.2)
${redirects}

# Clean URLs: /about serves about.html
RewriteCond %{REQUEST_URI} !\\.[A-Za-z0-9]+$
RewriteCond %{REQUEST_FILENAME}.html -f
RewriteRule ^(.+)$ $1.html [L]

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
  Header always set Strict-Transport-Security "max-age=31536000"
  Header always set Content-Security-Policy "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self' data:; form-action 'self'; frame-ancestors 'self'; base-uri 'self'; object-src 'none'"

  # Hashed build assets never change
  <If "%{REQUEST_URI} =~ m#^/_astro/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
  # Pages and documents: always revalidate
  <FilesMatch "\\.(html|xml|txt|pdf)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/xml application/javascript image/svg+xml font/otf
</IfModule>
${staging}`;
}

const legacy = JSON.parse(await readFile(join(SITE, 'tools', 'redirects', 'legacy.json'), 'utf8'));
await writeFile(join(SITE, 'dist', '.htaccess'), buildHtaccess(legacy));
console.log(`dist/.htaccess written (${legacyRedirects(legacy).length} legacy redirects)`);
